#!/usr/bin/env python3
"""Generate Trial Area corridor facades and check the Porymap-authored district."""

import argparse
import json
from collections import deque
from itertools import product

from PIL import Image

from generate_hub_tiles import render
from generate_portal_room import ROOT, Source, packed, words

AREA = 'Rogue_Area_TrialFrontier'
COLLISION = 0x0C00
METATILE = 0x03FF
STEPS = {'up': (0, -1), 'right': (1, 0), 'down': (0, 1), 'left': (-1, 0)}
BEHAVIORS = (0x64, 0x62, 0x65, 0x63)


def read(path):
    return json.loads((ROOT / path).read_text())


def point(event):
    return event['x'], event['y']


def cells(x1, y1, x2, y2):
    return {(x, y) for y in range(y1, y2 + 1) for x in range(x1, x2 + 1)}


def reachable(room, width, height, start, occupied):
    seen = {start}
    queue = deque([start])
    while queue:
        x, y = queue.popleft()
        for dx, dy in STEPS.values():
            nx, ny = neighbor = (x + dx, y + dy)
            if not (0 <= nx < width and 0 <= ny < height):
                continue
            if neighbor in seen or neighbor in occupied or room[ny * width + nx] & COLLISION:
                continue
            seen.add(neighbor)
            queue.append(neighbor)
    return seen


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()

    config = read('tools/data/trial_area.json')
    layouts = {row['id']: row for row in read('data/layouts/layouts.json')['layouts']}
    area = read(f'data/maps/{AREA}/map.json')
    layout = layouts[area['layout']]
    width, height = layout['width'], layout['height']
    room = words(layout['blockdata_filepath'])
    border = words(layout['border_filepath'])
    assert len(room) == width * height
    assert all(tile & COLLISION for tile in border)
    assert all(tile >> 12 == 3 for tile in room if not tile & COLLISION)
    assert area['map_type'] == 'MAP_TYPE_INDOOR'
    assert len(area['warp_events']) == 15 and len(area['object_events']) == 1
    assert len({point(event) for event in area['warp_events']}) == 15
    table = point(area['object_events'][0])
    warp = area['warp_events']
    arrival = point(warp[10])
    doors = {point(warp[i]) for i in (8, 9)}
    assert all(warp[i]['dest_map'] == 'MAP_ROGUE_INTERIOR_TRIAL_FRONTIER' for i in (8, 9))
    interior = read('data/maps/Rogue_Interior_TrialFrontier/map.json')
    assert interior['warp_events'][0]['dest_map'] == area['id']
    assert interior['warp_events'][0]['dest_warp_id'] == '8'
    assert arrival not in doors and arrival != table
    step_off = (warp[8]['x'], warp[8]['y'] + 1)

    source = Source('trial_architecture', 'trial_equipment')
    def behavior(tile):
        mid = tile & METATILE
        return source.attrs[mid // 512][mid % 512] & 0xFF

    assert all(behavior(room[y * width + x]) == 0x60 for x, y in doors)
    assert behavior(room[arrival[1] * width + arrival[0]]) == 0

    generated = {}
    functions = ['// Generated by scripts/generate_trial_area.py.\n',
                 'static const struct TrialAreaClosure sTrialAreaClosures[] =\n{\n']
    closures, lanes = [], []
    assert len(config['entrances']) == len(area['connections']) == len(BEHAVIORS)
    for entrance, connection, arrow in zip(config['entrances'], area['connections'], BEHAVIORS):
        direction = entrance['direction']
        map_name = f'Rogue_TrialCorridor_{direction}'
        facade = layouts[read(f'data/maps/{map_name}/map.json')['layout']]
        assert connection['map'] == 'MAP_ROGUE_TRIAL_CORRIDOR_' + direction.upper()
        assert (facade['width'], facade['height']) == (8, 8)
        assert all(facade[key] == layout[key] for key in ('primary_tileset', 'secondary_tileset'))
        side = connection['direction']
        off = connection['offset']
        horizontal = side in ('left', 'right')
        edge = {'up': 0, 'down': height - 1, 'left': 0, 'right': width - 1}[side]
        profile = [room[(off + i) * width + edge] if horizontal else room[edge * width + off + i]
                   for i in range(8)]
        generated[facade['blockdata_filepath']] = packed(
            [(profile[y if horizontal else x] | COLLISION) for y in range(8) for x in range(8)])
        generated[facade['border_filepath']] = packed(border)

        lane = {point(warp[i]) for i in entrance['warps']}
        assert len(lane) == 3
        dx, dy = STEPS[side]
        edge_lanes = set()
        for x, y in lane:
            assert abs((x if horizontal else y) - edge) == 2
            i = (y if horizontal else x) - off
            assert 0 < i < 7
            edge_lanes.add(i)
            assert behavior(room[y * width + x]) == arrow
            assert all(room[(y + dy * step) * width + x + dx * step] & COLLISION == 0
                       for step in (-1, 0, 1, 2))
            assert all(behavior(room[(y + dy * step) * width + x + dx * step]) == 0
                       for step in (-1, 1, 2))
        assert sorted(edge_lanes) == list(range(min(edge_lanes), min(edge_lanes) + 3))
        assert {i for i, tile in enumerate(profile) if not tile & COLLISION} == edge_lanes
        lanes.append(lane)

        patch = {}
        for x1, y1, x2, y2, name in entrance['closure']:
            mid = config['metatiles'][name]
            assert behavior(mid) == 0
            assert 0 <= x1 <= x2 < width and 0 <= y1 <= y2 < height
            patch.update({cell: mid for cell in cells(x1, y1, x2, y2)})
            functions.append(f'    {{HUB_AREA_CONN_{direction.upper()}, {x1}, {y1}, {x2}, {y2}, 0x{mid:03X}}},\n')
        assert lane <= patch.keys()
        assert all((x + dx * step, y + dy * step) in patch for x, y in lane for step in (1, 2))
        closures.append(patch)
    functions.append('};\n')
    generated['src/data/trial_area_closures.h'] = ''.join(functions).encode()

    occupied = {table}
    bench_approach = (table[0], table[1] + 1)
    for flags in product((False, True), repeat=4):
        state = room[:]
        for opened, patch in zip(flags, closures):
            if not opened:
                for (x, y), mid in patch.items():
                    state[y * width + x] = 0x3000 | COLLISION | mid
        assert not state[arrival[1] * width + arrival[0]] & COLLISION
        visited = reachable(state, width, height, arrival, occupied)
        assert doors | {bench_approach, step_off} <= visited
        walkable = {(i % width, i // width) for i, tile in enumerate(state) if not tile & COLLISION}
        assert walkable - occupied == visited, (flags, walkable - occupied - visited)
        for opened, lane in zip(flags, lanes):
            assert visited & lane == (lane if opened else set()), flags

    for filename, data in generated.items():
        path = ROOT / filename
        if args.check:
            assert path.read_bytes() == data, f'Stale Trial Area asset: {filename}'
        elif not path.exists() or path.read_bytes() != data:
            path.write_bytes(data)

    preview = Image.new('RGB', (width * 16, height * 16))
    images = {mid: render(source, mid) for mid in {v & METATILE for v in room}}
    for i, tile in enumerate(room):
        preview.paste(images[tile & METATILE], (16 * (i % width), 16 * (i // width)))
    table_sprite = Image.open(ROOT / 'graphics/object_events/pics/rogue/work_table.png')
    table_mask = table_sprite.point(lambda index: 255 if index else 0, 'L')
    preview.paste(table_sprite.convert('RGB'), (table[0] * 16 - 8, table[1] * 16 - 16), table_mask)
    dest = ROOT / 'build/trial_area'
    dest.mkdir(parents=True, exist_ok=True)
    preview.save(dest / 'open.png')
    print('Trial Area PASS: 16 connection states, 12 warp lanes, four facade seams, workbench and building approaches')


if __name__ == '__main__':
    main()
