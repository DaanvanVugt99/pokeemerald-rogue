bool8 RogueGift_IsDynamicUniqueAbilityEligible(u16 ability)
{
    u16 i;

    if(ability < DYNAMIC_UNIQUE_ABILITY_MIN || ability > DYNAMIC_UNIQUE_ABILITY_MAX)
        return FALSE;

    for(i = 0; i < ARRAY_COUNT(sExcludedDynamicUniqueAbilities); ++i)
    {
        if(sExcludedDynamicUniqueAbilities[i] == ability)
            return FALSE;
    }

    return TRUE;
}

u16 RogueGift_GetDynamicUniqueAbilityPoolCount(void)
{
    return DYNAMIC_UNIQUE_ABILITY_COUNT;
}

