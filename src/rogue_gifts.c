static u32 CreateDynamicMonId(u8 rarity, u16 species, bool8 ignoreTypingUnlockGate)
{
    u16 i;
    u32 temp;
    struct DynamicEvolutionFamily family = GetDynamicEvolutionFamily(species);
    struct CompressedDynamicData compressedDataUntyped = {0};

    switch (Random() % 2)
    {
    case 0:
        compressedDataUntyped.format = COMPRESSED_FORMAT_ORIGINAL;
        break;

    case 1:
        compressedDataUntyped.format = COMPRESSED_FORMAT_MON_TYPE;
        break;
    }

    if(compressedDataUntyped.format == COMPRESSED_FORMAT_MON_TYPE && !ignoreTypingUnlockGate && !RogueHub_HasUpgrade(HUB_UPGRADE_LAB_UNIQUE_TYPINGS))
        compressedDataUntyped.format = COMPRESSED_FORMAT_ORIGINAL;

    if(rarity == UNIQUE_RARITY_LEGENDARY)
    {
        if(compressedDataUntyped.format == COMPRESSED_FORMAT_MON_TYPE)
            compressedDataUntyped.format = COMPRESSED_FORMAT_MON_TYPE_UNIQUE_ABILITY;
        else
            compressedDataUntyped.format = COMPRESSED_FORMAT_ORIGINAL_UNIQUE_ABILITY;
    }

    // Start query with moves which are valid
    RogueCustomQuery_Begin();

    for (i = 0; i < DYNAMIC_EXOTIC_MOVE_COUNT; i++)
        RogueMiscQuery_EditElement(QUERY_FUNC_INCLUDE, sDynamicCustomMonMoves[i]);
    ExcludeDynamicFamilyMovesFromQuery(&family);

    if(compressedDataUntyped.format == COMPRESSED_FORMAT_ORIGINAL)
    {
        struct CompressedDynamicData_Original* compressedData = (struct CompressedDynamicData_Original*)&compressedDataUntyped;

        switch (rarity)
        {
        case UNIQUE_RARITY_COMMON:
            compressedData->moveSelection = SelectNextMoveSelection(species, 2);
            break;

        case UNIQUE_RARITY_RARE:
            compressedData->moveSelection = SelectNextMoveSelection(species, 1);
            compressedData->ability = SelectNextAbilityIndex(&family);
            break;

        case UNIQUE_RARITY_EPIC:
            compressedData->moveSelection = SelectNextMoveSelection(species, 2);
            compressedData->ability = SelectNextAbilityIndex(&family);
            break;

        default:
            AGB_ASSERT(FALSE);
            break;
        }
    }
    else if(compressedDataUntyped.format == COMPRESSED_FORMAT_ORIGINAL_UNIQUE_ABILITY)
    {
        struct CompressedDynamicData_OriginalUniqueAbility* compressedData = (struct CompressedDynamicData_OriginalUniqueAbility*)&compressedDataUntyped;

        switch (rarity)
        {
        case UNIQUE_RARITY_LEGENDARY:
        {
            u8 creationType = GetTypeBySpecies(species, 0, 0);
            u8 attempt;
            bool8 generated = FALSE;

            for(attempt = 0; attempt < 32 && !generated; ++attempt)
            {
                u16 moveIndices[2] = { SelectNextMoveIndex(species), SelectNextMoveIndex(species) };
                u8 abilitySeed;
                u16 moves[2] =
                {
                    sDynamicCustomMonMoves[moveIndices[0] - 1],
                    sDynamicCustomMonMoves[moveIndices[1] - 1],
                };
                struct SelectedDynamicSynergy synergy;

                compressedData->uniqueAbility = SelectNextUniqueAbility(&family, creationType);
                if(compressedData->uniqueAbility == ABILITY_CREATION)
                    synergy = SelectCreationSynergy(species, creationType, moves, ARRAY_COUNT(moves));
                else
                    synergy = SelectDynamicUniqueAbilitySynergy(species, compressedData->uniqueAbility, moves, ARRAY_COUNT(moves));

                if(synergy.move != MOVE_NONE)
                    moveIndices[Random() & 1] = GetDynamicMoveIndex(synergy.move);

                compressedData->moveSelection = EncodeDynamicMoveSelection(moveIndices[0], moveIndices[1]);
                generated = TrySelectLegendaryAbilitySeed(&family, compressedData->moveSelection, compressedData->uniqueAbility, compressedData->format, &abilitySeed);
                if(generated)
                    compressedData->abilitySeed = abilitySeed;
            }

            AGB_ASSERT(generated);
            break;
        }

        default:
            AGB_ASSERT(FALSE);
            break;
        }
    }
    else if(compressedDataUntyped.format == COMPRESSED_FORMAT_MON_TYPE)
    {
        struct CompressedDynamicData_MonType* compressedData = (struct CompressedDynamicData_MonType*)&compressedDataUntyped;
        compressedData->typeSlot = Random() % 2;
        compressedData->typeMoveChoice = Random() % 4;
        compressedData->type = SelectRandomType(species);
        compressedData->rarity = rarity;
        RogueMiscQuery_EditElement(QUERY_FUNC_EXCLUDE, SelectTypeBasedExtraMove(compressedData->type, compressedData->typeMoveChoice));

        switch (rarity)
        {
        case UNIQUE_RARITY_COMMON:
            break;

        case UNIQUE_RARITY_RARE:
            compressedData->payload = SelectNextMoveSelection(species, 2);
            break;

        case UNIQUE_RARITY_EPIC:
            compressedData->payload = SelectNextMoveIndex(species);
            compressedData->payload |= SelectNextAbilityIndex(&family) << 8;
            break;

        default:
            AGB_ASSERT(FALSE);
            break;
        }
    }
    else if(compressedDataUntyped.format == COMPRESSED_FORMAT_MON_TYPE_UNIQUE_ABILITY)
    {
        struct CompressedDynamicData_MonTypeUniqueAbility* compressedData = (struct CompressedDynamicData_MonTypeUniqueAbility*)&compressedDataUntyped;
        u8 typeSlot = Random() % 2;
        u8 typeMoveChoice = Random() % 4;
        u8 type = SelectRandomType(species);

        RogueMiscQuery_EditElement(QUERY_FUNC_EXCLUDE, SelectTypeBasedExtraMove(type, typeMoveChoice));

        switch (rarity)
        {
        case UNIQUE_RARITY_LEGENDARY:
        {
            u8 creationType = typeSlot == 0 ? type : GetTypeBySpecies(species, 0, 0);
            u16 typeMove = SelectTypeBasedExtraMove(type, typeMoveChoice);
            u8 attempt;
            bool8 generated = FALSE;

            compressedData->type = type;
            compressedData->typeSlot = typeSlot;
            compressedData->typeMoveChoice = typeMoveChoice;
            for(attempt = 0; attempt < 32 && !generated; ++attempt)
            {
                u16 moves[2];
                struct SelectedDynamicSynergy synergy;
                u16 abilitySelection;
                u8 abilitySeed;

                compressedData->moveIndex = SelectNextMoveIndex(species);
                moves[0] = typeMove;
                moves[1] = sDynamicCustomMonMoves[compressedData->moveIndex - 1];
                compressedData->uniqueAbility = SelectNextUniqueAbility(&family, creationType);
                if(compressedData->uniqueAbility == ABILITY_CREATION)
                    synergy = SelectCreationSynergy(species, creationType, moves, ARRAY_COUNT(moves));
                else
                    synergy = SelectDynamicUniqueAbilitySynergy(species, compressedData->uniqueAbility, moves, ARRAY_COUNT(moves));

                if(synergy.move != MOVE_NONE)
                    compressedData->moveIndex = GetDynamicMoveIndex(synergy.move);

                abilitySelection = compressedData->moveIndex
                    | (compressedData->typeMoveChoice << 8)
                    | (compressedData->typeSlot << 10)
                    | (compressedData->type << 11);
                generated = TrySelectLegendaryAbilitySeed(&family, abilitySelection, compressedData->uniqueAbility, compressedData->format, &abilitySeed);
                if(generated)
                    compressedData->abilitySeed = abilitySeed;
            }

            AGB_ASSERT(generated);
            break;
        }

        default:
            AGB_ASSERT(FALSE);
            break;
        }
    }
    else
    {
        AGB_ASSERT(FALSE);
    }

    RogueCustomQuery_End();

    temp = CompressedDynamicDataToCustomMonId(&compressedDataUntyped);
    temp |= (OTID_FLAG_CUSTOM_MON | OTID_FLAG_DYNAMIC_CUSTOM_MON);

#ifdef ROGUE_DEBUG
    // Ensure data (un)compresses correctly
    {
        struct DynamicMonData dynamicData = {0};

        UncompressDynamicMonData(temp, &dynamicData);
    }

#endif
    return temp;
}

