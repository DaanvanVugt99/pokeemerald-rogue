static u32 SelectNextAbilityIndex(const struct DynamicEvolutionFamily* family)
{
    // Give the mon a new ability for it
    while(TRUE)
    {
        u32 idx = (Random() % ARRAY_COUNT(sDynamicCustomMonAbilities));

        if(!IsNativeStandardAbility(family, sDynamicCustomMonAbilities[idx]))
            return 1 + idx;
    }

    return 0;
}

static u16 SelectNextUniqueAbility(const struct DynamicEvolutionFamily* family, u8 creationType)
{
    u16 ability;

    do
    {
        ability = DYNAMIC_UNIQUE_ABILITY_MIN + Random() % (DYNAMIC_UNIQUE_ABILITY_MAX - DYNAMIC_UNIQUE_ABILITY_MIN + 1);
    }
    while (!RogueGift_IsDynamicUniqueAbilityEligible(ability)
        || IsNativeUniqueAbility(family, ability)
        || (ability == ABILITY_CREATION && !HasCreationSynergyProfile(creationType)));

    return ability;
}

static bool8 TrySelectLegendaryAbilitySeed(const struct DynamicEvolutionFamily* family, u16 moveSelection, u16 uniqueAbility, u8 format, u8* outSeed)
{
    u8 initialSeed = Random() & 0x3;
    u8 offset;

    for(offset = 0; offset < 4; ++offset)
    {
        u8 seed = (initialSeed + offset) & 0x3;
        u16 ability = DecodeLegendaryStandardAbility(moveSelection, uniqueAbility, format, seed);

        if(!IsNativeStandardAbility(family, ability))
        {
            *outSeed = seed;
            return TRUE;
        }
    }

    return FALSE;
}

struct SelectedDynamicSynergy
{
    u16 move;
    u8 choice;
};

static bool8 DoesMoveMatchCreationSynergy(u8 type, u16 move)
{
    return move != MOVE_NONE
        && move < MOVES_COUNT
        && gBattleMoves[move].type == type
        && gBattleMoves[move].split == SPLIT_STATUS;
}

static struct SelectedDynamicSynergy SelectDynamicSynergyFromProfile(u16 species, u16 profileId, const u16* suppliedMoves, u8 suppliedMoveCount)
{
    struct SelectedDynamicSynergy selection = { MOVE_NONE, DYNAMIC_SYNERGY_CHOICE_NATURAL };
    struct DynamicSynergyProfile profile = GetDynamicSynergyProfile(profileId);
    u16 weights[3] = {0};
    u16 totalWeight = 0;
    u16 roll;
    u8 i;

    for(i = 0; i < suppliedMoveCount; ++i)
    {
        if(DoesMoveMatchDynamicSynergyProfile(profileId, suppliedMoves[i]))
            return selection;
    }

    for(i = 0; i < ARRAY_COUNT(profile.moves); ++i)
    {
        u16 move = profile.moves[i];

        if(move == MOVE_NONE)
            continue;

        if(gBattleMoves[move].split == SPLIT_PHYSICAL)
            weights[i] = max(1, gSpeciesInfo[species].baseAttack);
        else if(gBattleMoves[move].split == SPLIT_SPECIAL)
            weights[i] = max(1, gSpeciesInfo[species].baseSpAttack);
        else
            weights[i] = max(1, (gSpeciesInfo[species].baseAttack + gSpeciesInfo[species].baseSpAttack) / 2);

        totalWeight += weights[i];
    }

    if(totalWeight != 0)
    {
        roll = Random() % totalWeight;
        for(i = 0; i < ARRAY_COUNT(profile.moves); ++i)
        {
            if(roll < weights[i])
            {
                selection.choice = i;
                selection.move = profile.moves[i];
                break;
            }

            roll -= weights[i];
        }
    }

    return selection;
}

static struct SelectedDynamicSynergy SelectDynamicUniqueAbilitySynergy(u16 species, u16 ability, const u16* suppliedMoves, u8 suppliedMoveCount)
{
    if(ability == ABILITY_CREATION)
        return (struct SelectedDynamicSynergy){ MOVE_NONE, DYNAMIC_SYNERGY_CHOICE_NATURAL };

    return SelectDynamicSynergyFromProfile(species, GetDynamicUniqueAbilitySynergyProfileId(ability), suppliedMoves, suppliedMoveCount);
}

static struct SelectedDynamicSynergy SelectCreationSynergy(u16 species, u8 type, const u16* suppliedMoves, u8 suppliedMoveCount)
{
    struct SelectedDynamicSynergy selection = { MOVE_NONE, DYNAMIC_SYNERGY_CHOICE_NATURAL };
    struct DynamicSynergyProfile profile = GetCreationSynergyProfile(type);
    u16 weights[3] = {0};
    u16 totalWeight = 0;
    u16 roll;
    u8 i;

    for(i = 0; i < suppliedMoveCount; ++i)
    {
        if(DoesMoveMatchCreationSynergy(type, suppliedMoves[i]))
            return selection;
    }

    for(i = 0; i < ARRAY_COUNT(profile.moves); ++i)
    {
        u16 move = profile.moves[i];

        if(move == MOVE_NONE)
            continue;

        weights[i] = max(1, (gSpeciesInfo[species].baseAttack + gSpeciesInfo[species].baseSpAttack) / 2);
        totalWeight += weights[i];
    }

    if(totalWeight == 0)
        return selection;

    roll = Random() % totalWeight;
    for(i = 0; i < ARRAY_COUNT(profile.moves); ++i)
    {
        if(roll < weights[i])
        {
            selection.choice = i;
            selection.move = profile.moves[i];
            break;
        }
        roll -= weights[i];
    }

    return selection;
}

